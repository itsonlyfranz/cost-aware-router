"""Regenerate the README agent-flow diagram from the compiled LangGraph graph.

    python scripts/render_graph.py          # rewrite the diagram block in README.md
    python scripts/render_graph.py --check  # exit 1 if README.md is out of date

Offline: uses a stub client, so no API key is needed.
"""

import argparse
import sys
from pathlib import Path

from cost_aware_router.agent import CostAwareRouter
from cost_aware_router.client import FakeClient

README = Path(__file__).resolve().parent.parent / "README.md"
START = "<!-- flow-diagram:start (generated by scripts/render_graph.py) -->"
END = "<!-- flow-diagram:end -->"


def render_flow() -> str:
    """Mermaid source of the compiled router graph."""
    router = CostAwareRouter(FakeClient(lambda request: ""))
    return router.graph.get_graph().draw_mermaid().strip()


def flow_block() -> str:
    return f"{START}\n```mermaid\n{render_flow()}\n```\n{END}"


def splice(readme: str) -> str:
    """Replace the marked block in README text with a fresh diagram."""
    head, sep, rest = readme.partition(START)
    _, end_sep, tail = rest.partition(END)
    if not sep or not end_sep:
        raise ValueError("README.md is missing the flow-diagram start/end markers")
    return head + flow_block() + tail


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail instead of writing if README.md is stale")
    args = parser.parse_args()
    current = README.read_text(encoding="utf-8")
    updated = splice(current)
    if args.check:
        if updated != current:
            print("README flow diagram is stale; run: python scripts/render_graph.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
